# Converts the reviewed knowledge draft (kept outside the repo) to public/npc-knowledge.json
import re,json,sys
src=sys.argv[1] if len(sys.argv)>1 else '/workspace/emoji-world-private/drive-topics.md'
txt=open(src).read().split('## Knowledge base',1)[1]
entries=[];topics=[]
for blk in re.split(r'\n### ',txt)[1:]:
    head,body=blk.split('\n',1)
    m=re.match(r'\d+\.\s*(.+?)\s*(\[GEN[^\]]*\])?\s*\(keywords:\s*(.+?)\)',head)
    name=m.group(1).strip(); kw=[k.strip().lower() for k in m.group(3).split(',')]
    gen=bool(m.group(2)); topics.append({'topic':name,'gen':gen,'keywords':kw})
    for line in re.findall(r'^- (.+)$',body,re.M):
        m2=re.match(r'Q:\s*(.+?)\s+A:\s*(.+)$',line)
        if m2: q,a=m2.group(1),m2.group(2)
        else:
            m3=re.match(r'([^:]{2,40}):\s*(.+)$',line)
            if not m3: continue
            lab,a=m3.group(1).strip(),m3.group(2)
            q=('Any tips? ('+name+')') if re.search(r'tip|rule',lab,re.I) else 'Tell me about the '+lab.lower()+'.'
            if re.search(r'tip|rule|safety|example',lab,re.I): q=lab.capitalize()+' for '+name.lower()+'?'
            else: a=lab+': '+a
        entries.append({'topic':name,'q':q.strip(),'a':a.strip(),'keywords':kw})
T={t['topic'].split(' ')[0].lower():t['topic'] for t in topics}
def pick(*words): return [t['topic'] for t in topics if any(w in t['topic'].lower() for w in words)]
npcs=[
 {'id':'rahim','name':'Mr Rahim','role':'Workshop Technician','look':'tech1','topics':pick('workshop')},
 {'id':'salihin','name':'Mr Salihin','role':'Workshop Technician','look':'tech2','topics':pick('assembly','workshop')},
 {'id':'azmi','name':'Mr Azmi','role':'D&T Teacher - materials, joints & forming','look':'t1','topics':pick('resistant','joints','forming')},
 {'id':'huang','name':'Mr Huang','role':'D&T Teacher - electronics, mechanisms & structures','look':'t2','topics':pick('electronic','mechanism','structure')},
 {'id':'lau','name':'Mr Lau','role':'D&T Teacher - design, sketching, CAD & 3D printing','look':'t3','topics':pick('design process','3d','ergonom','sustain','biomim')},
 {'id':'nor','name':'Mr Nor Dnt','role':'D&T Teacher','look':'nor','topics':[t['topic'] for t in topics]},
]
json.dump({'note':'Generated by tools/make_knowledge.py. Topics marked gen=true are general D&T knowledge for Mr Nor to review.','topics':topics,'npcs':npcs,'entries':entries},open('public/npc-knowledge.json','w'),indent=1,ensure_ascii=False)
print(len(topics),'topics',len(entries),'entries',[ (n['id'],len(n['topics'])) for n in npcs])
